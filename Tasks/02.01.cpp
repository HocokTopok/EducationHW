#include <print>
#include <iostream>
#include <cmath>

////////////////////////////////////////////////////////////////

int main()
{
  const double sqrt5 = std::sqrt(5);

//  ------------------------------------------------------------

  const double fi = (1.0 + sqrt5) / 2;

  const double psi = (1.0 - sqrt5) / 2;
  
//  ------------------------------------------------------------

	size_t N = 0; std::cin >> N;

//  ------------------------------------------------------------

  int result = static_cast<int>(std::round((std::pow(fi, N) - std::pow(psi, N)) / sqrt(5)));

//  ------------------------------------------------------------

	std::print("{}", result);
}

