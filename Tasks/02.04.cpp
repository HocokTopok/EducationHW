int main()
{
  for (int num_1 = 1; num_1 < 10; ++num_1) {

    for (int num_2 = 0; num_2 < 10; ++num_2) {
      
      for (int num_3 = 0; num_3 < 10; ++num_3) {

//  ------------------------------------------------------------

        int number = num_1 * 100 + num_2 * 10 + num_3;
        
        int check = (num_1 * num_1 * num_1) + (num_2 * num_2 * num_2) + (num_3 * num_3 * num_3);

//  ------------------------------------------------------------

        if (number == check)
        {
          std::print("{} ", number);
        }
      }
    }
  }
}

